// Ajoute les fichiers à la page. "?v=" force le navigateur à prendre la dernière version.
function charger(liste) {
  const v = location.protocol == 'file:' ? '' : '?v=' + APPV;
  for (const f of liste)
    document.write(f.endsWith('.css') ? '<link rel="stylesheet" href="' + f + v + '">' : '<script src="' + f + v + '"><\/script>');
}
